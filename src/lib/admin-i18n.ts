/** Notes and messages that carry a name or a detail after a fixed Arabic phrase. */
const FR_PATTERNS: [RegExp, string][] = [
  [/^أُسند إلى (.+)$/u, "Attribuée à $1"],
  [/^تم دفع التسبيق بالبطاقة(.*)$/u, "Acompte payé par carte$1"],
  [/^رفض العميل الاستلام(.*)$/u, "Colis refusé par le client$1"],
  [/^بيانات غير صالحة: (.+)$/u, "Données invalides : $1"],
];

export function translate(lang: AdminLang, s: string, vars?: Record<string, string | number>) {
  let out = s;
  if (lang === "fr") {
    const hit = FR[s];
    if (hit !== undefined) out = hit;
    else for (const [re, to] of FR_PATTERNS) if (re.test(s)) { out = s.replace(re, to); break; }
  }
  return vars ? out.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : out;
}
